import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { buildPool, loadSeed } from './cover-pool-lib.mjs';

const SEED = process.env.DEEPWELL_SEED ?? join(homedir(), 'git_local/deepwell/apps/api/seed.sql');
const entries = buildPool(loadSeed(readFileSync(SEED, 'utf8')));
const out = { _generated: 'GENERATED by scripts/gen-cover-pool.mjs from ~/git_local/deepwell/apps/api/seed.sql — do not hand-edit; re-run pnpm cover:pool', entries };
writeFileSync('src/data/cover-pool.json', JSON.stringify(out, null, 2) + '\n');
console.log(`cover pool: ${entries.length} entries → src/data/cover-pool.json`);
